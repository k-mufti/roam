"""Tag rules and negation handling.

Tags are generated by weighted lexicon matching over review/comment text rather
than by an LLM classifier. That is a deliberate choice for v1: the vocabulary is
small and closed (~25 tags), the rules are auditable ("we tagged this 'quiet'
because these three comments said so"), and it costs nothing per place. An LLM
would generalize better to tags nobody enumerated, at the cost of being
unexplainable, non-deterministic, and metered.

## Negation is the whole problem

Naive substring matching gets these exactly backwards, and all four appear
verbatim in real Madrid review text:

    "Tiny, no laptops, in and out."          -> NOT laptop-friendly
    "Loud, fun, not a place for a quiet dinner."  -> NOT quiet
    "Not a romantic dinner, more of an event."    -> NOT date-night
    "Nightlife, not a bar."                       -> NOT bar-like

So every match is checked against a NegEx-style lookback window: a match is
discarded if a negator appears within `NEGATION_WINDOW_TOKENS` before it and no
clause boundary intervenes. This is the same technique clinical NLP uses for
"no evidence of pneumonia", and it is far cheaper than a parser.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

#: Words that flip the polarity of a following phrase.
NEGATORS = frozenset(
    {
        "no", "not", "never", "none", "without", "isnt", "isn't", "arent",
        "aren't", "wasnt", "wasn't", "dont", "don't", "doesnt", "doesn't",
        "didnt", "didn't", "cant", "can't", "cannot", "wont", "won't",
        "hardly", "barely", "avoid", "skip", "lacks", "lacking", "anything",
        "far", "less",
    }
)

#: How many tokens before a match to scan for a negator. 6 rather than 3-4
#: because English puts real distance between the two — "not a place for a
#: quiet dinner" has five tokens between "not" and "quiet". A window this wide
#: is only safe because of the clause-boundary guard below; without it,
#: "It's not cheap, but the quiet terrace is lovely" would negate "quiet".
NEGATION_WINDOW_TOKENS = 6

#: Punctuation that ends a clause, blocking negation from reaching across it.
#: Without this, "It's quiet. No music." would negate "quiet".
_CLAUSE_BOUNDARY = frozenset(
    {".", "!", "?", ";", ":", "but", "however", "though", "although"}
)

_TOKEN_RE = re.compile(r"[\w']+|[.!?;:]")


@dataclass(frozen=True, slots=True)
class TagRule:
    """One tag and the evidence that triggers it.

    `min_evidence_share` is a fraction of a place's *weighted* evidence, not a
    raw count: one upvoted comment calling a place quiet outweighs three
    unvoted ones, and a place with fifty snippets should need more than a single
    stray mention.
    """

    tag: str
    include: tuple[str, ...]
    #: Phrases that veto the tag outright, regardless of include matches.
    exclude: tuple[str, ...] = ()
    min_evidence_share: float = 0.18
    #: Require at least this mean sentiment across matching snippets.
    min_sentiment: float | None = None
    description: str = ""


