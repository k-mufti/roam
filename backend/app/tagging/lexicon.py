# --- matching ---------------------------------------------------------------


def _tokenize(text: str) -> list[str]:
    return _TOKEN_RE.findall(text.lower())


def _is_negated(tokens: list[str], match_index: int) -> bool:
    """Whether a negator precedes `match_index` within the lookback window,
    with no clause boundary in between."""
    start = max(0, match_index - NEGATION_WINDOW_TOKENS)
    for token in reversed(tokens[start:match_index]):
        if token in _CLAUSE_BOUNDARY:
            return False
        if token in NEGATORS:
            return True
    return False


def phrase_hits(text: str, phrase: str) -> int:
    """Count non-negated occurrences of `phrase` in `text`.

    Matching is token-based rather than substring-based so "line" does not match
    "online" and "date" does not match "update".
    """
    tokens = _tokenize(text)
    needle = _tokenize(phrase)
    if not needle:
        return 0
    hits = 0
    for i in range(len(tokens) - len(needle) + 1):
        if tokens[i : i + len(needle)] != needle:
            continue
        if _is_negated(tokens, i):
            continue
        hits += 1
    return hits


def matches_any(text: str, phrases: tuple[str, ...]) -> bool:
    """True if any phrase occurs, ignoring negation (used for vetoes).

    Vetoes match literally: the phrase "no laptops" *is* the negation, so
    running it through the negation filter would cancel it out.
    """
    tokens = _tokenize(text)
    for phrase in phrases:
        needle = _tokenize(phrase)
        if not needle:
            continue
        for i in range(len(tokens) - len(needle) + 1):
            if tokens[i : i + len(needle)] == needle:
                return True
    return False


@dataclass(slots=True)
class TagEvidence:
    """Why a tag was applied, for auditing and for the UI."""

    tag: str
    share: float
    matched_phrases: list[str] = field(default_factory=list)
    sample_snippets: list[str] = field(default_factory=list)
